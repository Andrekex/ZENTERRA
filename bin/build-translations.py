#!/usr/bin/env python3
"""Compile theme/languages/*.po into the files WordPress loads.

Edit the .po file, then run:  python3 bin/build-translations.py

Writes, next to each .po:
  <locale>.mo         read by every WordPress version
  <locale>.l10n.php   faster PHP format read by WordPress 6.5+
"""
import ast
import glob
import os
import re
import struct

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'theme', 'languages')


def parse_po(path):
    """Return {msgid: msgstr} plus the header entry under ''."""
    entries, key, cur, field = {}, None, None, None

    def unquote(s):
        return ast.literal_eval(s)

    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            m = re.match(r'(msgid|msgstr)\s+(".*")$', line)
            if m:
                if m.group(1) == 'msgid':
                    if key is not None:
                        entries[key] = cur
                    key, cur, field = unquote(m.group(2)), '', 'msgid'
                else:
                    cur, field = unquote(m.group(2)), 'msgstr'
            elif line.startswith('"'):
                if field == 'msgid':
                    key += unquote(line)
                else:
                    cur += unquote(line)
    if key is not None:
        entries[key] = cur
    return entries


def write_mo(entries, path):
    keys = sorted(entries)
    ids = [k.encode('utf-8') for k in keys]
    strs = [entries[k].encode('utf-8') for k in keys]
    n = len(keys)
    header = 7 * 4
    ids_table = header
    strs_table = ids_table + n * 8
    data = strs_table + n * 8
    id_offsets, str_offsets, blob = [], [], b''
    for s in ids:
        id_offsets.append((len(s), data + len(blob)))
        blob += s + b'\0'
    for s in strs:
        str_offsets.append((len(s), data + len(blob)))
        blob += s + b'\0'
    out = struct.pack('<7I', 0x950412DE, 0, n, ids_table, strs_table, 0, 0)
    out += b''.join(struct.pack('<2I', *o) for o in id_offsets)
    out += b''.join(struct.pack('<2I', *o) for o in str_offsets)
    out += blob
    with open(path, 'wb') as f:
        f.write(out)


def php_str(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def write_l10n_php(entries, path):
    headers = {}
    for line in entries.get('', '').split('\n'):
        if ':' in line:
            k, v = line.split(':', 1)
            headers[k.strip().lower()] = v.strip()
    messages = {k: v for k, v in entries.items() if k and v}
    lines = ['<?php', '// Generated by bin/build-translations.py from the .po file. Do not edit.', 'return array(']
    lines.append(f"\t'domain' => {php_str(headers.get('x-domain', 'zenterra'))},")
    lines.append(f"\t'language' => {php_str(headers.get('language', ''))},")
    lines.append(f"\t'plural-forms' => {php_str(headers.get('plural-forms', ''))},")
    lines.append("\t'messages' => array(")
    for k, v in messages.items():
        lines.append(f'\t\t{php_str(k)} => {php_str(v)},')
    lines.append('\t),')
    lines.append(');')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')


for po in sorted(glob.glob(os.path.join(ROOT, '*.po'))):
    entries = parse_po(po)
    base = po[:-3]
    write_mo(entries, base + '.mo')
    write_l10n_php(entries, base + '.l10n.php')
    print(f'{os.path.basename(po)}: {len([k for k in entries if k])} strings -> .mo, .l10n.php')
